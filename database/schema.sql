-- Esquema PostgreSQL para Neon.
-- Ejecutar una sola vez en la base de datos seleccionada en Neon.
BEGIN;

CREATE TABLE IF NOT EXISTS roles (
    id SMALLINT PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE
);

INSERT INTO roles (id, nombre) VALUES (1,'secretaria'),(2,'consulta')
ON CONFLICT (id) DO UPDATE SET nombre = EXCLUDED.nombre;

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    correo VARCHAR(190) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol_id SMALLINT NOT NULL REFERENCES roles(id),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS salones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    ubicacion VARCHAR(190),
    capacidad INTEGER NOT NULL DEFAULT 1 CHECK (capacidad > 0),
    descripcion TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS equipos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL UNIQUE,
    cantidad_total INTEGER NOT NULL DEFAULT 1 CHECK (cantidad_total > 0),
    descripcion TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS reservas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    salon_id BIGINT NOT NULL REFERENCES salones(id),
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    titulo VARCHAR(180) NOT NULL,
    solicitante VARCHAR(150) NOT NULL,
    dependencia VARCHAR(150),
    descripcion TEXT,
    fecha_inicio TIMESTAMP NOT NULL,
    fecha_fin TIMESTAMP NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente','confirmada','cancelada','finalizada')),
    motivo_cancelacion VARCHAR(500),
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (fecha_fin > fecha_inicio)
);

CREATE INDEX IF NOT EXISTS idx_reservas_rango
    ON reservas (salon_id, estado, fecha_inicio, fecha_fin);
CREATE INDEX IF NOT EXISTS idx_reservas_inicio ON reservas (fecha_inicio);

-- Impide solapamientos concurrentes en el mismo salón para reservas activas.
-- btree_gist es una extensión disponible en Neon.
CREATE EXTENSION IF NOT EXISTS btree_gist;
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'ex_reservas_salon_sin_solapamiento'
    ) THEN
        ALTER TABLE reservas ADD CONSTRAINT ex_reservas_salon_sin_solapamiento
        EXCLUDE USING gist (
            salon_id WITH =,
            tsrange(fecha_inicio, fecha_fin, '[)') WITH &&
        ) WHERE (estado IN ('pendiente','confirmada'));
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS reserva_equipos (
    reserva_id BIGINT NOT NULL REFERENCES reservas(id) ON DELETE CASCADE,
    equipo_id BIGINT NOT NULL REFERENCES equipos(id),
    cantidad INTEGER NOT NULL DEFAULT 1 CHECK (cantidad > 0),
    PRIMARY KEY (reserva_id, equipo_id)
);

CREATE TABLE IF NOT EXISTS auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    accion VARCHAR(80) NOT NULL,
    entidad VARCHAR(80) NOT NULL,
    entidad_id BIGINT,
    detalle JSONB,
    ip VARCHAR(45),
    user_agent VARCHAR(255),
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_auditoria_fecha ON auditoria (creado_en);

CREATE TABLE IF NOT EXISTS tokens_revocados (
    jti VARCHAR(100) PRIMARY KEY,
    expira_en TIMESTAMP NOT NULL,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_tokens_expira ON tokens_revocados (expira_en);

COMMIT;
